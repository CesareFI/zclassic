static bool sft_load(enum sft_variant v, uint8_t **m, size_t *n)
{
    char path[PATH_MAX];
    (void)snprintf(path, sizeof(path), "%s/%s.zsm", SFT_FIXTURES,
                   k_sft_edits[v].name);
    return sft_read(path, m, n);
}

