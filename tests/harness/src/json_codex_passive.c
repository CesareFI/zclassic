static bool cgot_p3_append(const char *bytes, size_t length)
{
    if (length > 65535 || cgot_p3.used + length + 4 > sizeof(cgot_p3.incoming)) return false;
    cgot_p3.incoming[cgot_p3.used++] = 0x81;
    if (length < 126) cgot_p3.incoming[cgot_p3.used++] = (unsigned char)length;
    else {
        cgot_p3.incoming[cgot_p3.used++] = 126;
        cgot_p3.incoming[cgot_p3.used++] = (unsigned char)(length >> 8);
        cgot_p3.incoming[cgot_p3.used++] = (unsigned char)length;
    }
    memcpy(cgot_p3.incoming + cgot_p3.used, bytes, length);
    cgot_p3.used += length; return true;
}
