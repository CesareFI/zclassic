static int cgot_p3_clock(clockid_t id, struct timespec *ts)
{
    (void)id; ts->tv_sec = 100; ts->tv_nsec = 0; return 0;
}
static ssize_t cgot_p3_read(int fd, void *p, size_t n)
{
    if (fd == 103) { memset(p, 0, n); return (ssize_t)n; }
    if (fd != 100) { cgot_p3.bad = 1; return -1; }
    size_t left = cgot_p3.used - cgot_p3.cursor;
    if (n > left) n = left;
    memcpy(p, cgot_p3.incoming + cgot_p3.cursor, n);
    cgot_p3.cursor += n; return (ssize_t)n;
}
static ssize_t cgot_p3_write_header(const unsigned char *b, size_t n)
{
    size_t z = 2;
    uint64_t length = b[1] & 127u;
    if (length == 126) { length = ((uint64_t)b[2] << 8) | b[3]; z = 4; }
    else if (length == 127) {
        length = 0;
        for (size_t i = 0; i < 8; i++) length = (length << 8) | b[2 + i];
        z = 10;
    }
    if (n != z + 4 || length >= 4096 || (b[0] & 15) != 1 || !(b[1] & 128)) {
        cgot_p3.bad = 1; return -1;
    }
    memcpy(cgot_p3.mask, b + z, 4);
    cgot_p3.declared = (size_t)length; cgot_p3.payload = 1; return (ssize_t)n;
}
static ssize_t cgot_p3_write(int fd, const void *p, size_t n)
{
    if (fd != 100) { cgot_p3.writes++; return -1; }
    if (n > 4 && !memcmp(p, "GET ", 4)) return (ssize_t)n;
    if (!cgot_p3.payload) return cgot_p3_write_header(p, n);
    if (n != cgot_p3.declared || cgot_p3.count >= 8) { cgot_p3.bad = 1; return -1; }
    const unsigned char *b = p;
    for (size_t i = 0; i < n; i++)
        cgot_p3.sent[cgot_p3.count][i] = (char)(b[i] ^ cgot_p3.mask[i % 4]);
    cgot_p3.sent[cgot_p3.count++][n] = 0;
    cgot_p3.payload = 0; return (ssize_t)n;
}
