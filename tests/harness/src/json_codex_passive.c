static bool cgot_rhett2_frames(void)
{
    cgot_p3_handshake();
    const char *init = "{\"id\":\"initialize\",\"result\":{}}";
    if (!cgot_p3_append(init, strlen(init))) return false;
    const unsigned char *bytes[] = { cgot_m1_response_0, cgot_m1_response_1, cgot_m1_response_2 };
    const size_t lengths[] = { sizeof(cgot_m1_response_0), sizeof(cgot_m1_response_1), sizeof(cgot_m1_response_2) };
    for (size_t i = 0; i < 3; i++) {
        char *copy = zcl_malloc(lengths[i], "cgot.rhett2.frame");
        if (!copy) return false;
        memcpy(copy, bytes[i], lengths[i]); cgot_rhett2_bytes(copy, lengths[i]);
        bool ok = cgot_p3_append(copy, lengths[i]); free(copy);
        if (!ok) return false;
    }
    return true;
}
