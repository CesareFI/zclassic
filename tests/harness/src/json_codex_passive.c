        ASSERT(strstr(requests[2], "\"itemsView\":\"notLoaded\""));
        ASSERT_EQ(cgo_passive_capture_v1(legs, 1, 2, 5000, &capture, why, sizeof(why)), CGA_OK);
        ASSERT_EQ(capture.trace[0].request_sha256.state, CGO_KNOWN);
