/* Mail pull count through the real mail leaf (outbox line accounting
 * without touching paths directly). */
static long long fmx_mail_count(void)
{
    struct fmx_call p;
    long long n = -1;
    json_init(&p.input);
    json_set_object(&p.input);
    memset(&p.request, 0, sizeof(p.request));
    p.request.input = &p.input;
    p.request.spec =
        zcl_command_registry_find(zcl_command_catalog(), "dev.agent.mail",
                                  NULL);
    zcl_command_reply_init(&p.reply, "zcl.agent_mail.v1");
    (void)json_push_kv_str(&p.input, "action", "pull");
    (void)json_push_kv_int(&p.input, "since", 0);
    zcl_native_handle_dev_agent_mail(&p.request, &p.reply);
    if (p.reply.status == ZCL_COMMAND_STATUS_PASSED) {
        const struct json_value *v = json_get(&p.reply.data, "count");
        if (v && v->type == JSON_INT)
            n = json_get_int(v);
    }
    zcl_command_reply_free(&p.reply);
    json_free(&p.input);
    return n;
}

