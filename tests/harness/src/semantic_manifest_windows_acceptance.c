/* ── shared golden vector (docs/work/SEMANTIC_MANIFEST.md) ───────────────
 * Byte-for-byte the same records as
 * tests/harness/src/test_semantic_manifest.c smt_golden_*(); a change to
 * either without the other is caught because the pinned constants below
 * would then disagree. */

#define SMWA_GOLDEN_LEN 775u
#define SMWA_GOLDEN_ROOT \
    "7ece87deea7ec79254851b5e02eef5f01ecc49829958ef22514208d026c6bb77"
#define SMWA_GOLDEN_HINT \
    "5b3caf953603b4c347bd0423e2d52a079d8b8c8b17d4fb22192a7b40a388baf6"

/* SHA3-256("zcl.semantic_manifest_windows_ledger.v1" || sorted "name root
 * hint" lines), one line per replayed fixture (see smwa_ledger below). The
 * Linux-native run (test_semantic_manifest.c smt_t_ledger) must produce the
 * identical digest over the identical fixture files read from disk. */
#define SMWA_LEDGER_DIGEST \
    "410a13f3370324250f7320d10113c87c75ce15d72289aa3e39340ea6222ba231"

static int g_failures;

static void smwa_fail(const char *what)
{
    fprintf(stderr, "semantic_manifest_windows_acceptance: FAIL: %s\n", what);
    g_failures++;
}

static void smwa_hex(const uint8_t *d, size_t n, char *out)
{
    static const char hx[] = "0123456789abcdef";
    for (size_t k = 0; k < n; k++) {
        out[2 * k] = hx[d[k] >> 4];
        out[2 * k + 1] = hx[d[k] & 15];
    }
    out[2 * n] = '\0';
}

/* ---- golden vector builder (matches test_semantic_manifest.c exactly) -- */

static void smwa_rec_texts(struct vcs_semantic_record_v1 *r,
                           const char *const *items, size_t n)
{
    vcs_semantic_record_v1_u32(r, (uint32_t)n);
    for (size_t k = 0; k < n; k++)
        vcs_semantic_record_v1_cstr(r, items[k]);
}

static bool smwa_golden_identity(struct vcs_semantic_builder_v1 *b,
                                 struct vcs_semantic_record_v1 *r)
{
    static const char *const argv[] = {"-std=c23", "-I@root/inc"};
    static const char *const angled[] = {"inc", "@sys/usr/include"};
    vcs_semantic_record_v1_reset(r);
    vcs_semantic_record_v1_cstr(r, "golden-cc 1.0");
    vcs_semantic_record_v1_cstr(r, "");
    vcs_semantic_record_v1_cstr(r, "x86_64-pc-linux-gnu");
    vcs_semantic_record_v1_cstr(r, "src/a.c");
    smwa_rec_texts(r, argv, 2);
    smwa_rec_texts(r, NULL, 0);
    smwa_rec_texts(r, angled, 2);
    smwa_rec_texts(r, NULL, 0);
    vcs_semantic_record_v1_u32(r, 2);
    vcs_semantic_record_v1_cstr(r, "CPATH");
    vcs_semantic_record_v1_u8(r, 0);
    vcs_semantic_record_v1_cstr(r, "");
    vcs_semantic_record_v1_cstr(r, "C_INCLUDE_PATH");
    vcs_semantic_record_v1_u8(r, 0);
    vcs_semantic_record_v1_cstr(r, "");
    return vcs_semantic_builder_v1_add(b, VCS_SEMANTIC_SECTION_V1_IDENTITY, r);
}

static bool smwa_golden_file(struct vcs_semantic_builder_v1 *b,
                             struct vcs_semantic_record_v1 *r,
                             const char *path, const char *body,
                             uint8_t origin)
{
    uint8_t d[32];
    zcl_sha3_256((const unsigned char *)body, strlen(body), d);
    vcs_semantic_record_v1_reset(r);
    vcs_semantic_record_v1_cstr(r, path);
    vcs_semantic_record_v1_digest(r, d);
    vcs_semantic_record_v1_u8(r, origin);
    return vcs_semantic_builder_v1_add(b, VCS_SEMANTIC_SECTION_V1_FILES, r);
}

